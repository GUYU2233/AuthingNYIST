#!/usr/bin/env python3
"""Generate static shell completions for nyist-connect from the CLI source.

The CLI is built on the standard library flag package, so the flag set lives in
internal/platform/{linux_cli.go,macos_cli.go}. Keeping the parser here means the
completions cannot silently drift when a flag is added or renamed.

Usage:
  python3 scripts/generate-completions.py            # rewrite completions/
  python3 scripts/generate-completions.py --check    # fail if committed files are stale

No third-party dependencies; no changes to internal/.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    "internal/platform/linux_cli.go",
    "internal/platform/macos_cli.go",
)
FLAG_RE = re.compile(r'flags\.(String|Bool)Var\([^,]+,\s*"([^"]+)"')
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")

# Value-completing flags. Their accepted values are defined by the CLI's own
# validation; flags not listed here are boolean (or take free-form input).
VALUE_CHOICES = {
    "autostart": ("enable", "disable", "status"),
    "network": ("auto", "nyist-tec", "nyist-stu"),
}
FILE_FLAGS = {"config"}

DESCRIPTIONS = {
    "autostart": "enable, disable or query autostart",
    "check-update": "check GitHub for the latest stable release",
    "config": "configuration file",
    "configure": "interactively configure the account (macOS)",
    "config-json": "print the configuration as JSON (macOS)",
    "connect": "authenticate and connect",
    "daemon": "run the keepalive loop in the foreground",
    "disconnect": "log out of the campus network",
    "doctor": "run read-only diagnostics",
    "network": "campus network profile",
    "save-config-stdin": "read a configuration JSON from stdin (macOS)",
    "status": "show read-only network status",
    "status-json": "show read-only status as JSON",
    "system": "use the root system service (Linux)",
    "tray": "show a tray icon and keep the session alive (Linux)",
    "version": "print the build version",
}

FILES = {
    "bash": "nyist-connect.bash",
    "zsh": "_nyist-connect",
    "fish": "nyist-connect.fish",
    "powershell": "nyist-connect.ps1",
}


def parse_flags(root):
    flags = {}
    for rel in SOURCES:
        text = (Path(root) / rel).read_text(encoding="utf-8")
        for kind, name in FLAG_RE.findall(text):
            if not NAME_RE.fullmatch(name):
                raise ValueError(f"unsupported flag name in {rel}: {name!r}")
            previous = flags.get(name)
            if previous is not None and previous != kind:
                raise ValueError(f"flag -{name} is both String and Bool")
            flags[name] = kind
    if not flags:
        raise ValueError("no CLI flags found; did the flag registration style change?")
    return dict(sorted(flags.items()))


def _words(flag):
    return [f"-{flag}", f"--{flag}"]


def render_bash(flags):
    names = [f"-{name} --{name}" for name in flags]
    lines = [
        "# bash completion for nyist-connect",
        "# Generated by scripts/generate-completions.py; do not edit by hand.",
        "",
        "_nyist_connect() {",
        "    local cur prev flag value",
        "    COMPREPLY=()",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        "",
        '    case "$prev" in',
    ]
    for flag, choices in VALUE_CHOICES.items():
        if flag not in flags:
            continue
        words = " ".join(choices)
        lines.append(f"        -{flag}|--{flag})")
        lines.append(f'            COMPREPLY=( $(compgen -W "{words}" -- "$cur") )')
        lines.append("            return 0")
        lines.append("            ;;")
    for flag in FILE_FLAGS:
        if flag not in flags:
            continue
        lines.append(f"        -{flag}|--{flag})")
        lines.append('            COMPREPLY=( $(compgen -f -- "$cur") )')
        lines.append("            return 0")
        lines.append("            ;;")
    lines += [
        "    esac",
        "",
        "    # Support the flag=value form accepted by Go's flag package.",
        '    case "$cur" in',
    ]
    for flag, choices in VALUE_CHOICES.items():
        if flag not in flags:
            continue
        words = " ".join(choices)
        lines += [
            f"        -{flag}=*|--{flag}=*)",
            '            flag="${cur%%=*}="',
            '            value="${cur#*=}"',
            f'            COMPREPLY=( $(compgen -W "{words}" -- "$value") )',
            '            COMPREPLY=( "${COMPREPLY[@]/#/$flag}" )',
            "            return 0",
            "            ;;",
        ]
    lines += [
        "    esac",
        "",
        '    if [[ "$cur" == -* ]]; then',
        f'        COMPREPLY=( $(compgen -W "{" ".join(names)}" -- "$cur") )',
        "    fi",
        "}",
        "",
        "complete -F _nyist_connect nyist-connect",
        "",
    ]
    return "\n".join(lines)


def render_zsh(flags):
    lines = [
        "#compdef nyist-connect",
        "# zsh completion for nyist-connect",
        "# Generated by scripts/generate-completions.py; do not edit by hand.",
        "",
        "_nyist_connect() {",
        "    _arguments -s \\",
        "        '(-h --help)'{-h,--help}'[show help]' \\",
    ]
    for name, kind in flags.items():
        desc = DESCRIPTIONS.get(name, f"set -{name}").replace("'", "")
        if name in VALUE_CHOICES:
            values = " ".join(VALUE_CHOICES[name])
            lines.append(f"        '(-{name} --{name})'{{-{name},--{name}}}'[{desc}]:value:({values})' \\")
        elif name in FILE_FLAGS:
            lines.append(f"        '(-{name} --{name})'{{-{name},--{name}}}'[{desc}]:file:_files' \\")
        elif kind == "Bool":
            lines.append(f"        '(-{name} --{name})'{{-{name},--{name}}}'[{desc}]' \\")
        else:
            lines.append(f"        '(-{name} --{name})'{{-{name},--{name}}}'[{desc}]:value:' \\")
    lines += [
        "}",
        "",
        '_nyist_connect "$@"',
        "",
    ]
    return "\n".join(lines)


def render_fish(flags):
    lines = [
        "# fish completion for nyist-connect",
        "# Generated by scripts/generate-completions.py; do not edit by hand.",
        "",
    ]
    for name, kind in flags.items():
        desc = DESCRIPTIONS.get(name, f"set -{name}").replace("'", "")
        # Fish's -o accepts the old single-letter style only; Go's flag package
        # also accepts --flag, so complete the long form here.
        if name in VALUE_CHOICES:
            values = " ".join(VALUE_CHOICES[name])
            lines.append(
                f"complete -c nyist-connect -l {name} -x -a \"{values}\" -d '{desc}'")
        elif name in FILE_FLAGS:
            lines.append(f"complete -c nyist-connect -l {name} -r -F -d '{desc}'")
        else:
            lines.append(f"complete -c nyist-connect -l {name} -d '{desc}'")
    lines.append("")
    return "\n".join(lines)


def render_powershell(flags):
    lines = [
        "# PowerShell completion for nyist-connect",
        "# Generated by scripts/generate-completions.py; do not edit by hand.",
        "",
        "using namespace System.Management.Automation",
        "",
        "Register-ArgumentCompleter -Native -CommandName 'nyist-connect' -ScriptBlock {",
        "    param($wordToComplete, $commandAst, $cursorPosition)",
        "",
        "    $flags = @(",
    ]
    for name in flags:
        quoted = ", ".join(f"'{w}'" for w in _words(name))
        lines.append(f"        {quoted},")
    lines += [
        "    )",
        "",
        "    $values = @{",
    ]
    for name, choices in VALUE_CHOICES.items():
        if name not in flags:
            continue
        for word in _words(name):
            quoted = ", ".join(f"'{c}'" for c in choices)
            lines.append(f"        '{word}' = @({quoted})")
    for name in FILE_FLAGS:
        if name in flags:
            lines.append(f"        '-{name}' = $null")
            lines.append(f"        '--{name}' = $null")
    lines += [
        "    }",
        "",
        "    $elements = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })",
        "    $previous = if ($elements.Count -ge 2) { $elements[-2] } else { '' }",
        "",
        "    if ($values.ContainsKey($previous)) {",
        "        $choices = $values[$previous]",
        "        if ($null -eq $choices) {",
        "            return",
        "        }",
        "        $choices | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object {",
        "            [CompletionResult]::new($_, $_, 'ParameterValue', $_)",
        "        }",
        "        return",
        "    }",
        "",
        "    $flags | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object {",
        "        [CompletionResult]::new($_, $_, 'ParameterName', $_)",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


RENDERERS = {
    "bash": render_bash,
    "zsh": render_zsh,
    "fish": render_fish,
    "powershell": render_powershell,
}


def generated(root):
    flags = parse_flags(root)
    return {name: RENDERERS[kind](flags) for kind, name in FILES.items()}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, help="default: ROOT/completions")
    parser.add_argument("--check", action="store_true", help="fail if committed completions are stale")
    args = parser.parse_args(argv)
    output = args.output or args.root / "completions"
    try:
        files = generated(args.root)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))

    if args.check:
        stale = []
        for name, text in files.items():
            path = output / name
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        if stale:
            print("Stale completions (run scripts/generate-completions.py):", file=sys.stderr)
            for path in stale:
                print(f"  {path}", file=sys.stderr)
            return 1
        print(f"Completions are up to date ({len(files)} files)")
        return 0

    output.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        path = output / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
    print(f"Wrote {len(files)} completion files to {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
