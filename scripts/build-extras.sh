#!/usr/bin/env bash
#
# Build the two maintainer-only archives. The release itself carries installers
# only (EXE, DMGs, deb/rpm); recipes, AUR, sandbox manifests, Arch packages,
# repository metadata and shell completions are grouped here and are NOT
# uploaded. They are useful for local or self-hosted packaging experiments.
#
#   cli-extras:       cli/    four portable terminal binaries
#                     docs/   README, NYIST-CONNECT, LICENSE, PACKAGING
#   packaging-extras: recipes/, aur/, sandbox/, packages/, repositories/,
#                     completions/
#
# cli-extras is built before the recipes are generated because the AUR,
# Flatpak, Snap, Homebrew, MacPorts and Nix recipes pin its checksum. That is
# also why the two groups are separate archives: a single archive would have to
# contain recipes that hash the archive containing them.
#
# Usage: VERSION=<version> bash scripts/build-extras.sh [cli|packaging|all]

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

usage() {
	printf 'usage: VERSION=<version> bash scripts/build-extras.sh [cli|packaging|all]\n' >&2
	exit 2
}

mode="${1:-all}"
case "$mode" in
	cli | packaging | all) ;;
	*) usage ;;
esac

: "${VERSION:?VERSION is required (for example VERSION=1.2.3)}"
version="${VERSION#v}"
if [[ ! "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$ ]]; then
	printf 'build-extras: refusing unsafe version: %s\n' "$VERSION" >&2
	exit 1
fi

dist="$root/dist"
[[ -d "$dist" ]] || { printf 'build-extras: missing dist directory\n' >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

require_file() {
	[[ -f "$1" && -s "$1" ]] || {
		printf 'build-extras: missing or empty required file: %s\n' "$1" >&2
		exit 1
	}
}

build_cli() {
	local stage="$tmp/cli-extras" archive
	archive="$dist/authingnyist-cli-extras-${version}.tar.gz"
	mkdir -p "$stage/cli" "$stage/docs"

	local binary
	for binary in nyist-connect-linux-amd64 nyist-connect-linux-arm64 \
		nyist-connect-macos-amd64 nyist-connect-macos-arm64; do
		require_file "$dist/$binary"
		cp "$dist/$binary" "$stage/cli/$binary"
	done

	require_file "$root/README.md"
	require_file "$root/NYIST-CONNECT.md"
	require_file "$root/LICENSE"
	require_file "$root/docs/PACKAGING.md"
	cp "$root/README.md" "$stage/docs/README.md"
	cp "$root/NYIST-CONNECT.md" "$stage/docs/NYIST-CONNECT.md"
	cp "$root/LICENSE" "$stage/docs/LICENSE"
	cp "$root/docs/PACKAGING.md" "$stage/docs/PACKAGING.md"

	rm -f "$archive"
	tar -czf "$archive" -C "$stage" cli docs
	printf 'build-extras: wrote %s\n' "$(basename "$archive")"
}

build_packaging() {
	local stage="$tmp/packaging-extras" archive
	archive="$dist/authingnyist-packaging-extras-${version}.tar.gz"
	mkdir -p "$stage"

	# Recipes are generated by scripts/generate-recipes.py and are mandatory.
	[[ -d "$dist/package-recipes" ]] || {
		printf 'build-extras: missing dist/package-recipes (run generate-recipes.py first)\n' >&2
		exit 1
	}
	cp -R "$dist/package-recipes" "$stage/recipes"
	if [[ -d "$root/completions" ]]; then
		cp -R "$root/completions" "$stage/completions"
	fi

	mkdir -p "$stage/aur" "$stage/sandbox" "$stage/packages" "$stage/repositories"

	# Copy only this release's files. Globbing every version would sweep stale
	# artifacts from earlier local builds into the published archive.
	local file
	for file in "$dist/nyist-connect-aur-${version}.tar.gz" \
		"$dist/authingnyist-sandbox-${version}.tar.gz" \
		"$dist/authingnyist-apt-repository-${version}.tar.gz" \
		"$dist/authingnyist-rpm-repository-${version}.tar.gz"; do
		if [[ -e "$file" ]]; then
			case "$file" in
				*aur*) cp "$file" "$stage/aur/" ;;
				*sandbox*) cp "$file" "$stage/sandbox/" ;;
				*) cp "$file" "$stage/repositories/" ;;
			esac
		fi
	done
	if [[ -f "$dist/linux-assets.txt" ]]; then
		while IFS= read -r file; do
			[[ "$file" == *.pkg.tar.zst ]] || continue
			require_file "$dist/$file"
			cp "$dist/$file" "$stage/packages/"
		done < "$dist/linux-assets.txt"
	fi

	rm -f "$archive"
	tar -czf "$archive" -C "$stage" .
	printf 'build-extras: wrote %s\n' "$(basename "$archive")"
}

case "$mode" in
	cli) build_cli ;;
	packaging) build_packaging ;;
	all)
		build_cli
		build_packaging
		;;
esac
