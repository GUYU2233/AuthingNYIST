#!/usr/bin/env python3
"""Generate the Homebrew Cask for the macOS DMGs.

The DMG built by scripts/build-macos.sh contains "NYIST Connect.app" with two
executables: NYIST-Connect (GUI) and nyist-core (CLI). The cask installs the app
and exposes the CLI as ``nyist-connect`` via a binary stanza.

Targets modern Homebrew (4.x) Cask DSL: per-architecture ``on_intel``/``on_arm``
blocks carrying their own ``sha256`` and ``url``.

Usage:
  python3 packaging/homebrew/generate_cask.py \
    --version 1.2.3 --tag v1.2.3 --dist dist \
    --output packaging/homebrew/Casks/nyist-connect.rb
"""
import argparse
import hashlib
import re
from pathlib import Path

BASE = "https://github.com/GUYU2233/AuthingNYIST/releases/download"
VERSION_RE = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")


def sha256_file(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def render(version, tag, repo, dmgs):
    """Return a cask file body.

    ``dmgs`` maps "amd64"/"arm64" to {"url": str, "sha256": str}. Both entries
    are required; a partial matrix would make one architecture uninstallable.
    """
    if not VERSION_RE.fullmatch(version):
        raise ValueError(f"invalid cask version: {version!r}")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo):
        raise ValueError(f"invalid repository: {repo!r}")
    if set(dmgs) != {"amd64", "arm64"}:
        raise ValueError("a cask needs both amd64 and arm64 DMGs")
    for arch, entry in dmgs.items():
        if not SHA_RE.fullmatch(entry.get("sha256", "")):
            raise ValueError(f"invalid sha256 for {arch}")
        if not entry.get("url", "").startswith("https://"):
            raise ValueError(f"invalid url for {arch}")

    lines = [
        "# Generated by packaging/homebrew/generate_cask.py from release DMGs.",
        "# Do not edit the checksums by hand; regenerate from the same build.",
        'cask "nyist-connect" do',
        f'  version "{version}"',
        "",
        "  on_intel do",
        f'    sha256 "{dmgs["amd64"]["sha256"]}"',
        f'    url "{dmgs["amd64"]["url"]}"',
        "  end",
        "",
        "  on_arm do",
        f'    sha256 "{dmgs["arm64"]["sha256"]}"',
        f'    url "{dmgs["arm64"]["url"]}"',
        "  end",
        "",
        '  name "NYIST Connect"',
        '  desc "NYIST campus network connector with GUI and nyist-connect CLI"',
        f'  homepage "https://github.com/{repo}"',
        "",
        '  depends_on macos: :ventura',
        "",
        '  app "NYIST Connect.app"',
        '  binary "#{appdir}/NYIST Connect.app/Contents/MacOS/nyist-core", target: "nyist-connect"',
        "",
        "  caveats <<~EOS",
        "    The app is ad-hoc signed but not notarized. If macOS blocks the first",
        "    launch, allow it under System Settings > Privacy & Security.",
        "  EOS",
        "end",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True, help="version without leading v")
    parser.add_argument("--tag", help="release tag (default vVERSION)")
    parser.add_argument("--dist", type=Path, default=Path("dist"))
    parser.add_argument("--repo", default="GUYU2233/AuthingNYIST")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)

    version = args.version.removeprefix("v")
    tag = args.tag or "v" + version
    dmgs = {}
    for arch in ("amd64", "arm64"):
        name = f"NYIST-Connect-macos-{arch}.dmg"
        path = args.dist / name
        if not path.is_file() or path.is_symlink() or path.stat().st_size == 0:
            parser.error(f"missing, empty, or symlink DMG: {path}")
        dmgs[arch] = {"name": name, "sha256": sha256_file(path), "url": f"{BASE}/{tag}/{name}"}
    try:
        text = render(version=version, tag=tag, repo=args.repo, dmgs=dmgs)
    except ValueError as exc:
        parser.error(str(exc))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"Generated cask for {version} at {args.output}")


if __name__ == "__main__":
    main()
